export type FrameworkModuleId =
  | 'ModelRuntime'
  | 'RigAnimator'
  | 'FXController'
  | 'SoundController'
  | 'StageConfig';

export interface GeneratedFrameworkModules {
  ModelRuntime: string;
  RigAnimator: string;
  FXController: string;
  SoundController: string;
  StageConfig: string;
}

export interface FrameworkGenerationContext {
  model: StudioSceneModel;
  activeParts: StudioPartNode[];
  uniquePartNames: Map<string, string>;
  scale: number;
  resampleTransforms?: boolean;
}

function round6(n: number): number {
  const r = Math.round(n * 1e6) / 1e6;
  return Object.is(r, -0) ? 0 : r;
}

function hexToRgb255(hex: string): [number, number, number] {
  const clean = hex.replace('#', '');
  if (clean.length !== 6) return [255, 255, 255];
  const r = parseInt(clean.slice(0, 2), 16);
  const g = parseInt(clean.slice(2, 4), 16);
  const b = parseInt(clean.slice(4, 6), 16);
  return [
    Number.isFinite(r) ? r : 255,
    Number.isFinite(g) ? g : 255,
    Number.isFinite(b) ? b : 255,
  ];
}

function makePivotTransformMatrix(
  pos: [number, number, number],
  rotDeg: [number, number, number],
  piv: [number, number, number],
  scaleFactor = 1
): THREE.Matrix4 {
  const eul = new THREE.Euler(
    THREE.MathUtils.degToRad(rotDeg[0]),
    THREE.MathUtils.degToRad(rotDeg[1]),
    THREE.MathUtils.degToRad(rotDeg[2]),
    'XYZ'
  );
  const t = new THREE.Matrix4().makeTranslation(
    (pos[0] + piv[0]) * scaleFactor,
    (pos[1] + piv[1]) * scaleFactor,
    (pos[2] + piv[2]) * scaleFactor
  );
  const r = new THREE.Matrix4().makeRotationFromEuler(eul);
  return t.multiply(r);
}

function mat4ToCFrameArgs(mat: THREE.Matrix4): string {
  const e = mat.elements;
  return [
    round6(e[12]), round6(e[13]), round6(e[14]),
    round6(e[0]), round6(e[4]), round6(e[8]),
    round6(e[1]), round6(e[5]), round6(e[9]),
    round6(e[2]), round6(e[6]), round6(e[10]),
  ].join(', ');
}

export function collectModelEffectsAndSounds(parts: StudioPartNode[]): {
  effects: { partId: string; partName: string; effect: StudioEffectNode }[];
  effectById: Map<string, { partId: string; effect: StudioEffectNode }>;
  sounds: { partId: string; sound: StudioSoundNode }[];
  soundById: Map<string, StudioSoundNode>;
} {
  const effects: { partId: string; partName: string; effect: StudioEffectNode }[] = [];
  const effectById = new Map<string, { partId: string; effect: StudioEffectNode }>();
  const sounds: { partId: string; sound: StudioSoundNode }[] = [];
  const soundById = new Map<string, StudioSoundNode>();

  for (const part of parts) {
    for (const fx of part.effects ?? []) {
      effects.push({ partId: part.id, partName: part.name, effect: fx });
      effectById.set(fx.id, { partId: part.id, effect: fx });
    }
    for (const snd of part.sounds ?? []) {
      sounds.push({ partId: part.id, sound: snd });
      soundById.set(snd.id, snd);
    }
  }
  return { effects, effectById, sounds, soundById };
}

/**
 * Generates StageConfig ModuleScript containing priorities, blend weights, markers,
 * and Motor6D Transform deltas + appearance keyframes.
 */
export function generateStageConfigModule(ctx: FrameworkGenerationContext): string {
  const { model, activeParts, uniquePartNames, scale, resampleTransforms } = ctx;
  const animations = (model.animations ?? []).filter(
    (c) => c.tracks.length > 0 || (c.markers?.length ?? 0) > 0
  );
  const activeMap = new Map(activeParts.map((p) => [p.id, p]));
  const { effectById, soundById } = collectModelEffectsAndSounds(activeParts);

  const lines: string[] = [
    `-- StageConfig (ModuleScript) — Generated by StudForge 3D`,
    `-- Holds AnimationPriority, FPS/sampling, Blend Weights, KeyframeMarkers, and Motor6D Transform deltas.`,
    `local StageConfig = {}`,
    ``,
    `StageConfig.ModelName = ${JSON.stringify(model.name.trim() || 'Model')}`,
    `StageConfig.PriorityTokens = {`,
  ];
  for (const [k, v] of Object.entries(ROBLOX_ANIMATION_PRIORITY_TOKENS)) {
    lines.push(`\t${k} = ${v},`);
  }
  lines.push(`}`);
  lines.push(``);
  lines.push(`StageConfig.Stages = {`);

  // Ensure world transforms stay warm for any reference queries
  solveWorldTransforms(activeParts);

  for (const clip of animations) {
    const priority = getClipPriority(clip);
    const fadeTime = round6(clip.fadeTime ?? 0.2);
    const defaultWeight = round6(clip.defaultWeight ?? 1);
    const times = getSampledClipTimes(clip, resampleTransforms);
    if (times[0] > 0.001) times.unshift(0);
    if (times[times.length - 1] < clip.duration - 0.001) times.push(round6(clip.duration));

    lines.push(`\t[${JSON.stringify(clip.name)}] = {`);
    lines.push(`\t\tDuration = ${round6(clip.duration)},`);
    lines.push(`\t\tFPS = ${clip.fps},`);
    lines.push(`\t\tLoop = ${clip.loop},`);
    lines.push(`\t\tPriority = Enum.AnimationPriority.${priority},`);
    lines.push(`\t\tPriorityName = ${JSON.stringify(priority)},`);
    lines.push(`\t\tFadeTime = ${fadeTime},`);
    lines.push(`\t\tDefaultWeight = ${defaultWeight},`);
    lines.push(`\t\tSampleMode = ${JSON.stringify(clip.sampleMode ?? (resampleTransforms ? 'resampled' : 'keyframes'))},`);

    // Markers (GetMarkerReachedSignal definitions)
    lines.push(`\t\tMarkers = {`);
    const markers = [...(clip.markers ?? [])].sort((a, b) => a.time - b.time);
    for (const m of markers) {
      const fxEntry = m.effectId ? effectById.get(m.effectId)?.effect : undefined;
      const sndEntry = m.soundId ? soundById.get(m.soundId) : undefined;
      lines.push(`\t\t\t{`);
      lines.push(`\t\t\t\tTime = ${round6(m.time)},`);
      lines.push(`\t\t\t\tName = ${JSON.stringify(m.name)},`);
      lines.push(`\t\t\t\tValue = ${JSON.stringify(m.value ?? '')},`);
      if (fxEntry) {
        lines.push(`\t\t\t\tEffectName = ${JSON.stringify(fxEntry.name)},`);
        lines.push(`\t\t\t\tEffectAction = ${JSON.stringify(m.effectAction ?? 'emit')},`);
        lines.push(`\t\t\t\tBurstCount = ${Math.max(1, m.burstCount ?? (fxEntry.kind === 'ParticleEmitter' ? fxEntry.burstCount : 12))},`);
      }
      if (sndEntry) {
        lines.push(`\t\t\t\tSoundName = ${JSON.stringify(sndEntry.name)},`);
      }
      lines.push(`\t\t\t},`);
    }
    lines.push(`\t\t},`);

    // Per-part tracks (delta Motor6D Transform for jointed parts + Size/Color/Transparency channels)
    lines.push(`\t\tTracks = {`);
    for (const tr of clip.tracks) {
      const part = activeMap.get(tr.partId);
      if (!part) continue;
      const uniqueName = uniquePartNames.get(part.id) ?? part.name;
      const piv = part.pivotOffset ?? [0, 0, 0];
      const isJointed = Boolean(part.parentId && activeMap.has(part.parentId));
      const restMat = makePivotTransformMatrix(part.position, part.rotation, piv, scale);
      const invRestMat = restMat.clone().invert();
      const sortedKfs = [...tr.keyframes].sort((a, b) => a.time - b.time);

      lines.push(`\t\t\t[${JSON.stringify(uniqueName)}] = {`);
      lines.push(`\t\t\t\tPartName = ${JSON.stringify(uniqueName)},`);
      lines.push(`\t\t\t\tIsJointed = ${isJointed},`);
      lines.push(`\t\t\t\tKeyframes = {`);

      for (const t of times) {
        const poseAtT = evaluatePartPoseAtTime(part, { ...clip, defaultWeight: 1 }, t);
        const poseMat = makePivotTransformMatrix(poseAtT.position, poseAtT.rotation, piv, scale);
        const deltaMat = invRestMat.clone().multiply(poseMat);

        // Find active segment easing + weight
        let activeKf = sortedKfs[0];
        for (const k of sortedKfs) {
          if (k.time <= t + 0.002) activeKf = k;
        }
        const style = activeKf?.easingStyle ?? 'Linear';
        const dir = activeKf?.easingDirection ?? 'Out';
        const isConstant = style === 'Constant';
        const safeStyle = style === 'Constant' ? 'Linear' : style;
        const [r, g, b] = hexToRgb255(poseAtT.color);

        const sizeX = round6(Math.max(0.05, poseAtT.size[0] * scale));
        const sizeY = round6(Math.max(0.05, poseAtT.size[1] * scale));
        const sizeZ = round6(Math.max(0.05, poseAtT.size[2] * scale));
        const actualSize: [number, number, number] =
          part.shape === 'Cylinder' || part.shape === 'LatheCone'
            ? [sizeY, sizeX, sizeZ]
            : [sizeX, sizeY, sizeZ];

        lines.push(`\t\t\t\t\t{`);
        lines.push(`\t\t\t\t\t\tTime = ${round6(t)},`);
        lines.push(`\t\t\t\t\t\tDeltaTransform = CFrame.new(${mat4ToCFrameArgs(deltaMat)}),`);
        lines.push(`\t\t\t\t\t\tWeight = ${round6(activeKf?.weight ?? 1)},`);
        lines.push(`\t\t\t\t\t\tEasingStyle = Enum.EasingStyle.${safeStyle},`);
        lines.push(`\t\t\t\t\t\tEasingDirection = Enum.EasingDirection.${dir},`);
        lines.push(`\t\t\t\t\t\tIsConstant = ${isConstant},`);
        lines.push(`\t\t\t\t\t\tSize = Vector3.new(${actualSize.join(', ')}),`);
        lines.push(`\t\t\t\t\t\tColor = Color3.fromRGB(${r}, ${g}, ${b}),`);
        lines.push(`\t\t\t\t\t\tTransparency = ${round6(poseAtT.transparency)},`);
        lines.push(`\t\t\t\t\t},`);
      }

      lines.push(`\t\t\t\t},`);
      lines.push(`\t\t\t},`);
    }
    lines.push(`\t\t},`);
    lines.push(`\t},`);
  }

  lines.push(`}`);
  lines.push(``);
  lines.push(`StageConfig.DefaultStage = ${JSON.stringify(animations[0]?.name ?? '')}`);
  lines.push(`return StageConfig`);

  return lines.join('\n');
}

/**
 * Generates FXController ModuleScript managing ParticleEmitters, Trails, and PointLights.
 */
export function generateFXControllerModule(ctx: FrameworkGenerationContext): string {
  const animations = ctx.model.animations ?? [];
  const { effectById } = collectModelEffectsAndSounds(ctx.activeParts);

  const markerMapLines: string[] = [];
  const seenMarkerPairs = new Set<string>();
  for (const clip of animations) {
    for (const m of clip.markers ?? []) {
      if (!m.effectId) continue;
      const fx = effectById.get(m.effectId)?.effect;
      if (!fx) continue;
      const key = `${m.name}|${fx.name}|${m.effectAction ?? 'emit'}`;
      if (seenMarkerPairs.has(key)) continue;
      seenMarkerPairs.add(key);
      markerMapLines.push(
        `\t[${JSON.stringify(m.name)}] = { EffectName = ${JSON.stringify(fx.name)}, Action = ${JSON.stringify(m.effectAction ?? 'emit')}, BurstCount = ${Math.max(1, m.burstCount ?? 20)} },`
      );
    }
  }

  return [
    `-- FXController (ModuleScript) — Generated by StudForge 3D`,
    `-- Drives ParticleEmitters, Trails, and PointLights and responds to KeyframeMarkers.`,
    `local TweenService = game:GetService("TweenService")`,
    `local FXController = {}`,
    ``,
    `FXController.MarkerBindings = {`,
    ...markerMapLines,
    `}`,
    ``,
    `function FXController.new(model: Model)`,
    `\tlocal self = {`,
    `\t\tModel = model,`,
    `\t\tEmitters = {} :: { [string]: ParticleEmitter },`,
    `\t\tTrails = {} :: { [string]: Trail },`,
    `\t\tLights = {} :: { [string]: PointLight },`,
    `\t\tBaseBrightness = {} :: { [string]: number },`,
    `\t}`,
    ``,
    `\tfor _, desc in ipairs(model:GetDescendants()) do`,
    `\t\tif desc:IsA("ParticleEmitter") then`,
    `\t\t\tself.Emitters[desc.Name] = desc`,
    `\t\telseif desc:IsA("Trail") then`,
    `\t\t\tself.Trails[desc.Name] = desc`,
    `\t\telseif desc:IsA("PointLight") then`,
    `\t\t\tself.Lights[desc.Name] = desc`,
    `\t\t\tself.BaseBrightness[desc.Name] = desc.Brightness`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:SetEnabled(name: string, enabled: boolean)`,
    `\t\tif self.Emitters[name] then`,
    `\t\t\tself.Emitters[name].Enabled = enabled`,
    `\t\tend`,
    `\t\tif self.Trails[name] then`,
    `\t\t\tself.Trails[name].Enabled = enabled`,
    `\t\tend`,
    `\t\tif self.Lights[name] then`,
    `\t\t\tself.Lights[name].Enabled = enabled`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:Emit(name: string, count: number?)`,
    `\t\tlocal emitter = self.Emitters[name]`,
    `\t\tif emitter then`,
    `\t\t\temitter:Emit(count or 20)`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:PulseLight(name: string, peakBrightness: number?, fadeDuration: number?)`,
    `\t\tlocal light = self.Lights[name]`,
    `\t\tif not light then return end`,
    `\t\tlocal base = self.BaseBrightness[name] or 1.5`,
    `\t\tlight.Enabled = true`,
    `\t\tlight.Brightness = peakBrightness or (base * 2.2)`,
    `\t\tlocal tw = TweenService:Create(light, TweenInfo.new(fadeDuration or 0.45, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), { Brightness = base })`,
    `\t\ttw:Play()`,
    `\tend`,
    ``,
    `\tfunction self:DisableTransient()`,
    `\t\tfor _, trail in pairs(self.Trails) do`,
    `\t\t\ttrail.Enabled = false`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:HandleMarker(markerName: string, _markerValue: string?, customBinding: { EffectName: string?, Action: string?, BurstCount: number? }?)`,
    `\t\tlocal binding = customBinding or FXController.MarkerBindings[markerName]`,
    `\t\tif not binding or not binding.EffectName then return end`,
    `\t\tlocal action = binding.Action or "emit"`,
    `\t\tif action == "emit" then`,
    `\t\t\tself:Emit(binding.EffectName, binding.BurstCount)`,
    `\t\telseif action == "enable" then`,
    `\t\t\tself:SetEnabled(binding.EffectName, true)`,
    `\t\telseif action == "disable" then`,
    `\t\t\tself:SetEnabled(binding.EffectName, false)`,
    `\t\telseif action == "pulse" then`,
    `\t\t\tself:PulseLight(binding.EffectName)`,
    `\t\t\tself:Emit(binding.EffectName, binding.BurstCount)`,
    `\t\tend`,
    `\tend`,
    ``,
    `\treturn self`,
    `end`,
    ``,
    `return FXController`,
  ].join('\n');
}

/**
 * Generates SoundController ModuleScript managing Audio Folder Sound instances synced to markers.
 */
export function generateSoundControllerModule(ctx: FrameworkGenerationContext): string {
  const animations = ctx.model.animations ?? [];
  const { soundById } = collectModelEffectsAndSounds(ctx.activeParts);

  const markerSoundLines: string[] = [];
  const seenPairs = new Set<string>();
  for (const clip of animations) {
    for (const m of clip.markers ?? []) {
      if (!m.soundId) continue;
      const snd = soundById.get(m.soundId);
      if (!snd) continue;
      const key = `${m.name}|${snd.name}`;
      if (seenPairs.has(key)) continue;
      seenPairs.add(key);
      markerSoundLines.push(`\t[${JSON.stringify(m.name)}] = ${JSON.stringify(snd.name)},`);
    }
  }

  return [
    `-- SoundController (ModuleScript) — Generated by StudForge 3D`,
    `-- Resolves Sound instances inside the Package Audio Folder and plays them on KeyframeMarkers.`,
    `local SoundController = {}`,
    ``,
    `SoundController.MarkerBindings = {`,
    ...markerSoundLines,
    `}`,
    ``,
    `function SoundController.new(packageRoot: Instance, model: Model)`,
    `\tlocal self = {`,
    `\t\tSounds = {} :: { [string]: Sound },`,
    `\t}`,
    ``,
    `\tlocal audioFolder = packageRoot:FindFirstChild("Audio")`,
    `\tif audioFolder then`,
    `\t\tfor _, child in ipairs(audioFolder:GetDescendants()) do`,
    `\t\t\tif child:IsA("Sound") then`,
    `\t\t\t\tself.Sounds[child.Name] = child`,
    `\t\t\tend`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfor _, desc in ipairs(model:GetDescendants()) do`,
    `\t\tif desc:IsA("Sound") and not self.Sounds[desc.Name] then`,
    `\t\t\tself.Sounds[desc.Name] = desc`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:Play(name: string, pitchJitter: number?)`,
    `\t\tlocal snd = self.Sounds[name]`,
    `\t\tif not snd then return end`,
    `\t\tlocal baseSpeed = snd:GetAttribute("BaseSpeed") or snd.PlaybackSpeed`,
    `\t\tsnd:SetAttribute("BaseSpeed", baseSpeed)`,
    `\t\tif pitchJitter and pitchJitter > 0 then`,
    `\t\t\tsnd.PlaybackSpeed = baseSpeed * (1 + (math.random() * 2 - 1) * pitchJitter)`,
    `\t\tend`,
    `\t\tsnd.TimePosition = 0`,
    `\t\tsnd:Play()`,
    `\tend`,
    ``,
    `\tfunction self:StopAll()`,
    `\t\tfor _, snd in pairs(self.Sounds) do`,
    `\t\t\tif snd.IsPlaying then`,
    `\t\t\t\tsnd:Stop()`,
    `\t\t\tend`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:HandleMarker(markerName: string, explicitSoundName: string?)`,
    `\t\tlocal targetName = explicitSoundName or SoundController.MarkerBindings[markerName]`,
    `\t\tif targetName then`,
    `\t\t\tself:Play(targetName, 0.05)`,
    `\t\tend`,
    `\tend`,
    ``,
    `\treturn self`,
    `end`,
    ``,
    `return SoundController`,
  ].join('\n');
}

/**
 * Generates RigAnimator ModuleScript supporting BOTH native Animator + GetMarkerReachedSignal
 * and immediate Motor6D.Transform + C0/C1 weighted procedural playback.
 */
export function generateRigAnimatorModule(): string {
  return [
    `-- RigAnimator (ModuleScript) — Generated by StudForge 3D`,
    `-- Supports native Animator + GetMarkerReachedSignal AND procedural Motor6D.Transform weighted playback.`,
    `local RunService = game:GetService("RunService")`,
    `local TweenService = game:GetService("TweenService")`,
    `local StageConfig = require(script.Parent:WaitForChild("StageConfig"))`,
    ``,
    `local RigAnimator = {}`,
    ``,
    `function RigAnimator.new(model: Model)`,
    `\tlocal self = {`,
    `\t\tModel = model,`,
    `\t\tJoints = {} :: { [string]: Motor6D },`,
    `\t\tParts = {} :: { [string]: BasePart },`,
    `\t\tAnimator = nil :: Animator?,`,
    `\t\tActiveTracks = {} :: { [string]: AnimationTrack },`,
    `\t\tCurrentStage = nil :: string?,`,
    `\t\tElapsed = 0,`,
    `\t\tWeightBlend = 1,`,
    `\t\tFadeAlpha = 1,`,
    `\t\tMarkerCallbacks = {} :: { (markerName: string, markerValue: string, markerData: any) -> () },`,
    `\t\t_hbConn = nil :: RBXScriptConnection?,`,
    `\t}`,
    ``,
    `\tfor _, desc in ipairs(model:GetDescendants()) do`,
    `\t\tif desc:IsA("Motor6D") and desc.Part1 then`,
    `\t\t\tself.Joints[desc.Part1.Name] = desc`,
    `\t\telseif desc:IsA("BasePart") then`,
    `\t\t\tself.Parts[desc.Name] = desc`,
    `\t\telseif desc:IsA("Animator") then`,
    `\t\t\tself.Animator = desc`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tfunction self:OnMarkerReached(fn: (markerName: string, markerValue: string, markerData: any) -> ())`,
    `\t\ttable.insert(self.MarkerCallbacks, fn)`,
    `\tend`,
    ``,
    `\tlocal function dispatchMarker(markerName: string, markerValue: string, markerData: any)`,
    `\t\tfor _, cb in ipairs(self.MarkerCallbacks) do`,
    `\t\t\ttask.spawn(cb, markerName, markerValue, markerData)`,
    `\t\tend`,
    `\tend`,
    ``,
    `\t-- Bind native Roblox Animation object via Animator + GetMarkerReachedSignal`,
    `\tfunction self:BindPublishedAnimation(stageName: string, animationObj: Animation): AnimationTrack?`,
    `\t\tif not self.Animator then return nil end`,
    `\t\tlocal stage = StageConfig.Stages[stageName]`,
    `\t\tlocal track = self.Animator:LoadAnimation(animationObj)`,
    `\t\tif stage then`,
    `\t\t\ttrack.Priority = stage.Priority`,
    `\t\t\ttrack.Looped = stage.Loop`,
    `\t\t\tfor _, m in ipairs(stage.Markers) do`,
    `\t\t\t\ttrack:GetMarkerReachedSignal(m.Name):Connect(function(paramValue)`,
    `\t\t\t\t\tdispatchMarker(m.Name, paramValue or m.Value, m)`,
    `\t\t\t\tend)`,
    `\t\t\tend`,
    `\t\tend`,
    `\t\tself.ActiveTracks[stageName] = track`,
    `\t\treturn track`,
    `\tend`,
    ``,
    `\tfunction self:PlayStage(stageName: string, weightOverride: number?)`,
    `\t\tlocal stage = StageConfig.Stages[stageName]`,
    `\t\tif not stage then`,
    `\t\t\twarn("[RigAnimator] Unknown stage:", stageName)`,
    `\t\t\treturn`,
    `\t\tend`,
    `\t\tif self.ActiveTracks[stageName] then`,
    `\t\t\tfor name, tr in pairs(self.ActiveTracks) do`,
    `\t\t\t\tif name ~= stageName and tr.IsPlaying then tr:Stop(stage.FadeTime) end`,
    `\t\t\tend`,
    `\t\t\tself.ActiveTracks[stageName]:Play(stage.FadeTime, weightOverride or stage.DefaultWeight)`,
    `\t\t\treturn`,
    `\t\tend`,
    `\t\tself.CurrentStage = stageName`,
    `\t\tself.Elapsed = 0`,
    `\t\tself.FadeAlpha = stage.FadeTime > 0 and 0 or 1`,
    `\t\tself.WeightBlend = weightOverride or stage.DefaultWeight or 1`,
    `\tend`,
    ``,
    `\tfunction self:Stop()`,
    `\t\tself.CurrentStage = nil`,
    `\t\tfor _, joint in pairs(self.Joints) do`,
    `\t\t\tjoint.Transform = CFrame.new()`,
    `\t\tend`,
    `\t\tfor _, tr in pairs(self.ActiveTracks) do`,
    `\t\t\tif tr.IsPlaying then tr:Stop(0.15) end`,
    `\t\tend`,
    `\tend`,
    ``,
    `\tlocal function evaluateKeyframesAtTime(keyframes: { any }, t: number, blendWeight: number)`,
    `\t\tlocal n = #keyframes`,
    `\t\tif n == 0 then return nil end`,
    `\t\tif t <= keyframes[1].Time then`,
    `\t\t\tlocal k = keyframes[1]`,
    `\t\t\tlocal w = math.clamp((k.Weight or 1) * blendWeight, 0, 1)`,
    `\t\t\treturn CFrame.new():Lerp(k.DeltaTransform, w), k.Size, k.Color, k.Transparency`,
    `\t\tend`,
    `\t\tif t >= keyframes[n].Time then`,
    `\t\t\tlocal k = keyframes[n]`,
    `\t\t\tlocal w = math.clamp((k.Weight or 1) * blendWeight, 0, 1)`,
    `\t\t\treturn CFrame.new():Lerp(k.DeltaTransform, w), k.Size, k.Color, k.Transparency`,
    `\t\tend`,
    `\t\tfor i = 1, n - 1 do`,
    `\t\t\tlocal k0, k1 = keyframes[i], keyframes[i + 1]`,
    `\t\t\tif t >= k0.Time and t <= k1.Time then`,
    `\t\t\t\tlocal span = math.max(1e-5, k1.Time - k0.Time)`,
    `\t\t\t\tlocal alpha = math.clamp((t - k0.Time) / span, 0, 1)`,
    `\t\t\t\tlocal eased = k0.IsConstant and (alpha >= 1 and 1 or 0) or TweenService:GetValue(alpha, k0.EasingStyle, k0.EasingDirection)`,
    `\t\t\t\tlocal rawDelta = k0.DeltaTransform:Lerp(k1.DeltaTransform, eased)`,
    `\t\t\t\tlocal kWeight = (k0.Weight or 1) + ((k1.Weight or 1) - (k0.Weight or 1)) * eased`,
    `\t\t\t\tlocal w = math.clamp(kWeight * blendWeight, 0, 1)`,
    `\t\t\t\tlocal finalTransform = CFrame.new():Lerp(rawDelta, w)`,
    `\t\t\t\tlocal size = k0.Size:Lerp(k1.Size, eased)`,
    `\t\t\t\tlocal color = k0.Color:Lerp(k1.Color, eased)`,
    `\t\t\t\tlocal transp = k0.Transparency + (k1.Transparency - k0.Transparency) * eased`,
    `\t\t\t\treturn finalTransform, size, color, transp`,
    `\t\t\tend`,
    `\t\tend`,
    `\t\treturn nil`,
    `\tend`,
    ``,
    `\tself._hbConn = RunService.Heartbeat:Connect(function(dt: number)`,
    `\t\tlocal stageName = self.CurrentStage`,
    `\t\tif not stageName then return end`,
    `\t\tlocal stage = StageConfig.Stages[stageName]`,
    `\t\tif not stage or stage.Duration <= 0 then return end`,
    ``,
    `\t\tlocal prevT = self.Elapsed`,
    `\t\tlocal nextT = prevT + dt`,
    `\t\tlocal wrapped = false`,
    `\t\tif nextT >= stage.Duration then`,
    `\t\t\tif stage.Loop then`,
    `\t\t\t\tnextT = nextT % stage.Duration`,
    `\t\t\t\twrapped = true`,
    `\t\t\telse`,
    `\t\t\t\tnextT = stage.Duration`,
    `\t\t\tend`,
    `\t\tend`,
    `\t\tself.Elapsed = nextT`,
    `\t\tif stage.FadeTime > 0 then`,
    `\t\t\tself.FadeAlpha = math.min(1, self.FadeAlpha + dt / stage.FadeTime)`,
    `\t\telse`,
    `\t\t\tself.FadeAlpha = 1`,
    `\t\tend`,
    `\t\tlocal effectiveBlend = self.WeightBlend * self.FadeAlpha`,
    ``,
    `\t\t-- Fire KeyframeMarker events crossed during this frame`,
    `\t\tfor _, m in ipairs(stage.Markers) do`,
    `\t\t\tlocal hit = if wrapped`,
    `\t\t\t\tthen (m.Time > prevT and m.Time <= stage.Duration) or (m.Time >= 0 and m.Time <= nextT)`,
    `\t\t\t\telseif prevT == 0 then (m.Time >= 0 and m.Time <= nextT)`,
    `\t\t\t\telse (m.Time > prevT and m.Time <= nextT)`,
    `\t\t\tif hit then`,
    `\t\t\t\tdispatchMarker(m.Name, m.Value, m)`,
    `\t\t\tend`,
    `\t\tend`,
    ``,
    `\t\t-- Apply Motor6D.Transform (preserving C0/C1 rest offsets) & part appearance channels`,
    `\t\tfor partName, track in pairs(stage.Tracks) do`,
    `\t\t\tlocal deltaCf, size, color, transp = evaluateKeyframesAtTime(track.Keyframes, nextT, effectiveBlend)`,
    `\t\t\tif deltaCf then`,
    `\t\t\t\tlocal joint = self.Joints[partName]`,
    `\t\t\t\tif joint then`,
    `\t\t\t\t\tjoint.Transform = deltaCf`,
    `\t\t\t\tend`,
    `\t\t\t\tlocal part = self.Parts[partName]`,
    `\t\t\t\tif part then`,
    `\t\t\t\t\tpart.Size = size`,
    `\t\t\t\t\tpart.Color = color`,
    `\t\t\t\t\tpart.Transparency = transp`,
    `\t\t\t\tend`,
    `\t\t\tend`,
    `\t\tend`,
    `\tend)`,
    ``,
    `\tfunction self:Destroy()`,
    `\t\tif self._hbConn then`,
    `\t\t\tself._hbConn:Disconnect()`,
    `\t\t\tself._hbConn = nil`,
    `\t\tend`,
    `\t\tself:Stop()`,
    `\tend`,
    ``,
    `\treturn self`,
    `end`,
    ``,
    `return RigAnimator`,
  ].join('\n');
}

/**
 * Generates ModelRuntime entry Script placed inside PackageFolder/Scripts.
 */
export function generateModelRuntimeScript(ctx: FrameworkGenerationContext): string {
  const safeModelName = ctx.model.name.trim() || 'Model';
  const animations = (ctx.model.animations ?? []).filter(
    (c) => c.tracks.length > 0 || (c.markers?.length ?? 0) > 0
  );
  const stageList = animations.map((c) => c.name).join(', ') || 'None';

  return [
    `-- ModelRuntime (Script) — Generated by StudForge 3D`,
    `-- Place inside <PackageFolder>/Scripts alongside RigAnimator, FXController, SoundController, and StageConfig.`,
    `-- Available stages: ${stageList}`,
    `local scriptsFolder = script.Parent`,
    `local packageRoot = scriptsFolder.Parent`,
    `local model = packageRoot:FindFirstChild(${JSON.stringify(safeModelName)}) or packageRoot:FindFirstChildWhichIsA("Model")`,
    `assert(model, "[ModelRuntime] Could not locate target Model inside package folder.")`,
    ``,
    `local StageConfig = require(scriptsFolder:WaitForChild("StageConfig"))`,
    `local RigAnimator = require(scriptsFolder:WaitForChild("RigAnimator"))`,
    `local FXController = require(scriptsFolder:WaitForChild("FXController"))`,
    `local SoundController = require(scriptsFolder:WaitForChild("SoundController"))`,
    ``,
    `local animator = RigAnimator.new(model)`,
    `local fx = FXController.new(model)`,
    `local audio = SoundController.new(packageRoot, model)`,
    ``,
    `-- Route GetMarkerReachedSignal & Motor6D timeline markers to FX & Audio`,
    `animator:OnMarkerReached(function(markerName, markerValue, markerData)`,
    `\tfx:HandleMarker(markerName, markerValue, if markerData and markerData.EffectName then {`,
    `\t\tEffectName = markerData.EffectName,`,
    `\t\tAction = markerData.EffectAction,`,
    `\t\tBurstCount = markerData.BurstCount,`,
    `\t} else nil)`,
    `\taudio:HandleMarker(markerName, if markerData then markerData.SoundName else nil)`,
    `end)`,
    ``,
    `-- Expose attribute-driven stage switching in Studio/Live servers:`,
    `-- packageRoot:SetAttribute("Stage", "Attack")`,
    `packageRoot:GetAttributeChangedSignal("Stage"):Connect(function()`,
    `\tlocal requested = packageRoot:GetAttribute("Stage")`,
    `\tif typeof(requested) == "string" and requested ~= "" then`,
    `\t\tfx:DisableTransient()`,
    `\t\tanimator:PlayStage(requested)`,
    `\tend`,
    `end)`,
    ``,
    `if StageConfig.DefaultStage ~= "" then`,
    `\tpackageRoot:SetAttribute("Stage", StageConfig.DefaultStage)`,
    `\tanimator:PlayStage(StageConfig.DefaultStage)`,
    `end`,
  ].join('\n');
}

export function generateAllFrameworkModules(
  ctx: FrameworkGenerationContext
): GeneratedFrameworkModules {
  return {
    ModelRuntime: generateModelRuntimeScript(ctx),
    RigAnimator: generateRigAnimatorModule(),
    FXController: generateFXControllerModule(ctx),
    SoundController: generateSoundControllerModule(ctx),
    StageConfig: generateStageConfigModule(ctx),
  };
}
