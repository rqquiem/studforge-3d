export function createNewPart(shape: PartShape, index: number): StudioPartNode {
  const catalog = SHAPE_CATALOG.find((c) => c.shape === shape) ?? SHAPE_CATALOG[0];
  const [sx, sy, sz] = catalog.defaultSize;
  const offsetX = ((index % 5) - 2) * 1.5;
  const offsetZ = (Math.floor(index / 5) % 3) * 1.5;
  const uid = `part_${Date.now().toString(36)}_${index}`;

  return {
    id: uid,
    name: `${catalog.label.replace(/\s+/g, '')}_${index + 1}`,
    shape,
    parentId: null,
    pivotOffset: [0, 0, 0],
    position: [offsetX, sy / 2, offsetZ],
    rotation: [0, 0, 0],
    size: [sx, sy, sz],
    color: shape === 'LatheCone' || shape === 'BevelPlate' ? '#635F62' : '#2563EB',
    material: shape === 'BevelPlate' || shape === 'PipeElbow' ? 'Metal' : 'SmoothPlastic',
    transparency: 0,
    reflectance: 0,
    anchored: true,
    canCollide: true,
    castShadow: true,
    visible: true,
  };
}
